"""Batch bookkeeping for the research agents, and the human-readable LEDGER.md it regenerates.

    python ledger.py launch K001 [K002 ...]   mark batches as running (the orchestrator calls this as it launches)
    python ledger.py finish K001 [...]        validate each agent file, count what it found, mark done / partial
    python ledger.py                          just regenerate LEDGER.md
"""
import json
import sys
from pathlib import Path

from common import AGENT_OUT, BATCHES, BATCH_CAP, HERE, load, now, progress, save, PROGRESS

LEDGER = HERE / "LEDGER.md"


def agent_file(b):
    f = AGENT_OUT / f"{b}.json"
    if not f.exists():
        return None
    try:
        return json.loads(f.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {"objects": [], "_broken": True}


def summarise(b, keys):
    from merge import check_file
    d = agent_file(b)
    if d is None:
        return {"objects": 0, "done": 0, "rv": 0, "pm": 0, "wiki": 0, "complete": False, "errors": []}
    objs = d.get("objects", [])
    return {"objects": len(objs), "done": sum(1 for o in objs if o.get("done")),
            "rv": sum(1 for o in objs if o.get("rv")), "pm": sum(1 for o in objs if o.get("pm")),
            "wiki": sum(1 for o in objs for w in ("rv", "pm") if (o.get(w) or {}).get("wikipedia")),
            "complete": bool(d.get("complete")) and {o.get("key") for o in objs if o.get("done")} >= set(keys),
            "errors": ["file is not valid JSON"] if d.get("_broken") else check_file(d, b)}


def regenerate():
    p = progress()
    batches = (load(BATCHES) or {}).get("batches", {})
    lines = ["# Known within 100ly -- motion research ledger", "",
             "Regenerated by `ledger.py`; the machine state is `progress.json`. Run `python status.py` for what to do next.",
             "", f"Cap: {BATCH_CAP} batches of {len(next(iter(batches.values()), []))} (decided 2026-10-08). "
             f"Brightest first, so later batches are fainter and likely to yield less.", "",
             "| Batch | State | Launched | Finished | Objects done | RV found | PM found | Wikipedia | Written | Notes |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for b, keys in batches.items():
        s = p["batches"].get(b, {})
        lines.append(f"| {b} | {s.get('state', 'pending')} | {s.get('launched', '')[:16]} | {s.get('finished', '')[:16]} | "
                     f"{s.get('done', '')}/{len(keys)} | {s.get('rv', '')} | {s.get('pm', '')} | {s.get('wiki', '')} | "
                     f"{s.get('written', '')} | {s.get('note', '')} |")
    lines += ["", "## For the user's judgement", ""]
    lines += [f"- {x}" for x in p.get("judgement", [])] or ["- (nothing yet)"]
    if p.get("decided"):
        lines += ["", "## Decided by the user", ""] + [f"- {x}" for x in p["decided"]]
    LEDGER.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    args = sys.argv[1:]
    batches = (load(BATCHES) or {}).get("batches", {})
    if args and args[0] in ("launch", "finish"):
        p = progress()
        for b in args[1:]:
            assert b in batches, b
            s = p["batches"].setdefault(b, {})
            if args[0] == "launch":
                s.update(state="running", launched=now())
                s.pop("written", None)
            else:
                info = summarise(b, batches[b])
                s.update(state="done" if info["complete"] and not info["errors"] else "partial", finished=now(),
                         **{k: info[k] for k in ("done", "rv", "pm", "wiki")})
                s["errors"] = info["errors"][:20]
                print(b, s["state"], {k: info[k] for k in ("objects", "done", "rv", "pm", "wiki")},
                      ("errors: " + "; ".join(info["errors"][:5])) if info["errors"] else "")
        save(PROGRESS, p)
    regenerate()


if __name__ == "__main__":
    main()
